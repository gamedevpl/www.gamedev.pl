type PixelIconProps = {
  name: PixelIconName;
  size?: number;
  className?: string;
  title?: string;
};

export function PixelIcon({ name, size = 16, className, title }: PixelIconProps) {
  const rows = ICONS[name];
  const rects: ReactElement[] = [];
  for (let y = 0; y < rows.length; y++) {
    const row = rows[y];
    for (let x = 0; x < row.length; x++) {
      if (row[x] === '#') {
        rects.push(<rect key={`${x}-${y}`} x={x} y={y} width={1} height={1} />);
      }
    }
  }
  return (
    <svg
      className={className}
      width={size}
      height={size}
      viewBox={`0 0 ${G} ${G}`}
      fill="currentColor"
      shapeRendering="crispEdges"
      role={title ? 'img' : 'presentation'}
      aria-hidden={title ? undefined : true}
      aria-label={title}
      data-icon={name}
      focusable="false"
      style={{ display: 'inline-block', verticalAlign: '-0.15em', flex: 'none' }}
    >
      {title ? <title>{title}</title> : null}
      {rects}
    </svg>
  );
}
